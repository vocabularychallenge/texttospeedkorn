import re
import shutil
import subprocess
import tempfile
from io import BytesIO
from pathlib import Path

import streamlit as st
from gtts import gTTS

st.set_page_config(page_title="Thai + English TTS", page_icon="🔊", layout="centered")
st.title("🔊 อ่านข้อความเป็นเสียง")
st.caption("Google gTTS • ภาษาไทย + English • ดาวน์โหลด MP3")

MAX_CHARS = 3000
MAX_SEGMENT_CHARS = 180


def split_by_language(text: str) -> list[tuple[str, str]]:
    tokens = re.findall(
        r"[\u0E00-\u0E7F]+|[A-Za-z]+(?:['’][A-Za-z]+)*|\d+(?:[.,]\d+)*|\s+|[^\w\s]+|.",
        text,
    )
    chunks: list[tuple[str, str]] = []
    current_lang = "th"
    for token in tokens:
        if re.search(r"[\u0E00-\u0E7F]", token):
            lang = "th"
        elif re.search(r"[A-Za-z]", token):
            lang = "en"
        else:
            lang = current_lang
        if chunks and chunks[-1][0] == lang:
            chunks[-1] = (lang, chunks[-1][1] + token)
        else:
            chunks.append((lang, token))
        current_lang = lang
    return [(lang, phrase.strip()) for lang, phrase in chunks if phrase.strip()]


def split_long_phrase(phrase: str, limit: int = MAX_SEGMENT_CHARS) -> list[str]:
    result = []
    while len(phrase) > limit:
        cut = max((phrase.rfind(sep, 0, limit + 1) for sep in (" ", "\n", ".", ",", "!", "?", "。", "，")), default=-1)
        cut = cut + 1 if cut >= limit // 3 else limit
        part = phrase[:cut].strip()
        if part:
            result.append(part)
        phrase = phrase[cut:]
    if phrase.strip():
        result.append(phrase.strip())
    return result


@st.cache_data(ttl=3600, max_entries=24, show_spinner=False)
def create_mp3(text: str, slow: bool) -> bytes:
    if not text.strip():
        raise ValueError("กรุณากรอกข้อความ")
    if len(text) > MAX_CHARS:
        raise ValueError(f"ข้อความต้องไม่เกิน {MAX_CHARS:,} ตัวอักษร")
    if not shutil.which("ffmpeg"):
        raise RuntimeError("ไม่พบ FFmpeg บนเซิร์ฟเวอร์ กรุณาตรวจสอบ packages.txt")

    chunks = [
        (lang, part)
        for lang, phrase in split_by_language(text)
        for part in split_long_phrase(phrase)
    ]
    if not chunks:
        raise ValueError("ไม่มีข้อความให้อ่าน")

    with tempfile.TemporaryDirectory(prefix="gtts_") as directory:
        folder = Path(directory)
        segment_paths = []
        for index, (lang, part) in enumerate(chunks):
            path = folder / f"segment_{index:04d}.mp3"
            # Google gTTS requires an internet connection.
            gTTS(text=part, lang=lang, slow=slow).save(str(path))
            segment_paths.append(path)

        if len(segment_paths) == 1:
            return segment_paths[0].read_bytes()

        # Filenames are generated by this program (not supplied by users).
        concat_file = folder / "concat.txt"
        concat_file.write_text(
            "".join(f"file '{path.name}'\n" for path in segment_paths),
            encoding="utf-8",
        )
        output_path = folder / "speech.mp3"
        command = [
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
            "-f", "concat", "-safe", "1", "-i", str(concat_file),
            "-vn", "-codec:a", "libmp3lame", "-b:a", "128k", str(output_path),
        ]
        try:
            completed = subprocess.run(command, capture_output=True, text=True, timeout=120, check=False)
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError("รวมไฟล์เสียงนานเกินกำหนด กรุณาลองข้อความที่สั้นลง") from exc
        if completed.returncode != 0 or not output_path.is_file() or output_path.stat().st_size == 0:
            raise RuntimeError("FFmpeg รวมไฟล์ MP3 ไม่สำเร็จ: " + completed.stderr[-350:])
        return output_path.read_bytes()


text = st.text_area(
    "ข้อความที่ต้องการให้อ่าน",
    placeholder="สวัสดีค่ะ วันนี้เราจะเรียนคำว่า Cat และ Dog",
    height=180,
    max_chars=MAX_CHARS,
)
slow = st.checkbox("อ่านช้า (Slow)")
st.caption(f"{len(text):,} / {MAX_CHARS:,} ตัวอักษร • ต้องใช้อินเทอร์เน็ต")

request = (text.strip(), slow)
if st.session_state.get("last_request") != request:
    st.session_state["mp3_data"] = None

if st.button("สร้างเสียง MP3", type="primary", disabled=not text.strip(), use_container_width=True):
    try:
        with st.spinner("กำลังสร้างเสียงและรวมไฟล์ MP3..."):
            st.session_state["mp3_data"] = create_mp3(*request)
        st.session_state["last_request"] = request
        st.success("สร้างเสียงสำเร็จ")
    except Exception as exc:
        st.session_state["mp3_data"] = None
        st.error(f"สร้างเสียงไม่สำเร็จ: {exc}")

if st.session_state.get("mp3_data") is not None:
    st.audio(st.session_state["mp3_data"], format="audio/mpeg")
    st.download_button(
        "⬇️ ดาวน์โหลด MP3",
        data=st.session_state["mp3_data"],
        file_name="thai_english_speech.mp3",
        mime="audio/mpeg",
        use_container_width=True,
    )
